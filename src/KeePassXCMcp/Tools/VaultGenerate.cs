using System.ComponentModel;
using KeePassXCMcp.Infra;
using ModelContextProtocol.Server;

namespace KeePassXCMcp.Tools;

[McpServerToolType]
public static class VaultGenerateTool
{
    [McpServerTool(Name = "vault_generate")]
    [Description(
        "Create a NEW secret (F1): the password is generated INSIDE keepassxc-cli and staged " +
        "directly — you never see or type its value, and nothing has been exposed to any model " +
        "(recorded as provenance 'generated'). Use this instead of inventing keys in the " +
        "conversation: a key you can see is a key that leaked. Staged only — promote to move " +
        "it into the main vault. Returns the entry path, a fingerprint, and length — never the " +
        "value. To change an existing entry's value use vault_rotate.")]
    public static async Task<string> RunAsync(
        [Description("Entry label path in the staging database, e.g. 'Services/webhook-secret'. Groups are created if missing.")] string label,
        [Description("Password length, 6-128. Default 32.")] int length = 32,
        [Description("Include lowercase letters (default true).")] bool lower = true,
        [Description("Include uppercase letters (default true).")] bool upper = true,
        [Description("Include digits (default true).")] bool numeric = true,
        [Description("Include special characters (default true).")] bool special = true,
        [Description("Optional notes body for the entry.")] string? notes = null)
    {
        try
        {
            var profile = new GenProfile(length)
            {
                Lower = lower, Upper = upper, Numeric = numeric, Special = special,
                EveryGroup = lower && upper && numeric && special,
            };
            var receipt = await SecretOps.GenerateAsync(
                VaultContext.Config, VaultContext.Paths, VaultContext.Cli, VaultContext.Staging, label, profile, notes);
            return "Generated by keepassxc-cli and staged (main vault untouched; value never left the binary).\n" +
                   "Promote to move it into the vault. To use the value now: the consumer must get it from the vault, " +
                   "not from this conversation — this flow is value-free by design.\n" +
                   StagingOps.ToJson(receipt);
        }
        catch (Exception ex) when (ex is ArgumentException or KeePassCliException or InvalidOperationException)
        {
            return "Error: " + Redact.Apply(ex.Message, VaultContext.Config.KnownSecrets);
        }
    }
}
