using System.ComponentModel;
using KeePassXCMcp.Infra;
using ModelContextProtocol.Server;

namespace KeePassXCMcp.Tools;

[McpServerToolType]
public static class VaultRotateTool
{
    [McpServerTool(Name = "vault_rotate")]
    [Description(
        "Rotate a STAGED entry's secret (F10): keepassxc-cli regenerates the password in " +
        "place — you never see the new value — and the provenance record flips to " +
        "'generated' (the old fingerprint is kept as retired). This is how the vault_audit " +
        "list empties: rotate what was exposed. Main-vault rotation = the same flow: the " +
        "entry is rotated on the staged copy and the human promotes it; never bypassed.")]
    public static async Task<string> RunAsync(
        [Description("Entry label path of the staged entry, e.g. 'Services/webhook-secret'.")] string label,
        [Description("New password length, 6-128. Default 32.")] int length = 32,
        [Description("Include lowercase letters (default true).")] bool lower = true,
        [Description("Include uppercase letters (default true).")] bool upper = true,
        [Description("Include digits (default true).")] bool numeric = true,
        [Description("Include special characters (default true).")] bool special = true)
    {
        try
        {
            var profile = new GenProfile(length)
            {
                Lower = lower, Upper = upper, Numeric = numeric, Special = special,
                EveryGroup = lower && upper && numeric && special,
            };
            var receipt = await SecretOps.RotateAsync(
                VaultContext.Config, VaultContext.Paths, VaultContext.Cli, VaultContext.Staging, label, profile);
            return "Password regenerated by keepassxc-cli inside the staged entry (value never left the binary). " +
                   "Provenance updated to 'generated'; promote to move it into the vault and update the service.\n" +
                   StagingOps.ToJson(receipt);
        }
        catch (Exception ex) when (ex is ArgumentException or KeePassCliException or InvalidOperationException)
        {
            return "Error: " + Redact.Apply(ex.Message, VaultContext.Config.KnownSecrets);
        }
    }
}
