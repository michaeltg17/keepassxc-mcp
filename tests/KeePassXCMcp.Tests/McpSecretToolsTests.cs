using KeePassXCMcp.Infra;
using ModelContextProtocol.Client;
using ModelContextProtocol.Protocol;

namespace KeePassXCMcp.Tests;

/// <summary>MCP-protocol e2e for the new 0.3.0 tools: tool list, value-free receipts,
/// seen-by-model tagging, rotation clearing the audit, and reader-session guidance when
/// no read session exists.</summary>
public class McpSecretToolsTests
{
    private static string Text(CallToolResult result) =>
        string.Join("\n", result.Content.OfType<TextContentBlock>().Select(c => c.Text));

    private static async Task<McpClient> ConnectAsync(VaultHarness harness)
    {
        var transport = new StdioClientTransport(new StdioClientTransportOptions
        {
            Name = "keepassxc-mcp",
            Command = VaultHarness.ServerExePath,
            Arguments = ["mcp"],
            EnvironmentVariables = new Dictionary<string, string?> { ["KEEPASSXC_MCP_CONFIG"] = harness.Paths.ConfigFile },
        });
        return await McpClient.CreateAsync(transport);
    }

    [RequiresCliFact]
    public async Task ToolList_IncludesNewFlowTools()
    {
        using var harness = await VaultHarness.CreateAsync();
        await using var client = await ConnectAsync(harness);
        var names = (await client.ListToolsAsync()).Select(t => t.Name).ToList();

        // Exact surface, not "each of these is present": an accidental extra or silently
        // dropped tool fails here too. Order is transport-defined, so set equality is the
        // strongest true statement about the list.
        names.Should().BeEquivalentTo(new[]
        {
            "vault_generate", "vault_stage_value", "vault_rotate",
            "vault_audit", "vault_audit_dismiss",
            "vault_reader_open", "vault_reader_close", "vault_search", "vault_get",
            // pre-existing tools stay:
            "vault_stage_entry", "vault_list_staged", "vault_staged_remove", "vault_promote", "vault_open_approver",
        });
    }

    [RequiresCliFact]
    public async Task Generate_Then_Rotate_ReplacesValue_ClearsExposure()
    {
        using var harness = await VaultHarness.CreateAsync();
        await using var client = await ConnectAsync(harness);

        var gen = Text(await client.CallToolAsync("vault_generate", new Dictionary<string, object?>
        {
            ["label"] = "Svcs/toolgen",
            ["length"] = 24,
        }));
        // One receipt contract: markers in, value out — chained so a leak fails the same
        // assertion that verifies the receipt, not in a detached follow-up.
        gen.Should().Contain("Generated by keepassxc-cli").And.Contain("Svcs/toolgen");

        var value1 = (await harness.Cli.ReadAttributeAsync(
            harness.StagingPath, VaultHarness.StagingPassword, null, "Svcs/toolgen", "Password")).TrimEnd('\r', '\n');
        value1.Should().HaveLength(24);
        gen.Should().NotContain(value1); // value-free receipt

        var rot = Text(await client.CallToolAsync("vault_rotate", new Dictionary<string, object?>
        {
            ["label"] = "Svcs/toolgen",
            ["length"] = 40,
        }));

        var value2 = (await harness.Cli.ReadAttributeAsync(
            harness.StagingPath, VaultHarness.StagingPassword, null, "Svcs/toolgen", "Password")).TrimEnd('\r', '\n');
        value2.Should().NotBe(value1).And.HaveLength(40);
        rot.Should().Contain("regenerated").And.NotContain(value2);

        // provenance: still generated, old fingerprint retired → audit clean.
        var prov = ProvenanceStore.Load(harness.Paths);
        var rec = Assert.Single(prov.Records);
        rec.Origin.Should().Be(Origin.Generated);
        rec.RetiredFingerprints.Should().Contain(Hashing.Sha256Hex(value1));
        rec.FingerprintSha256.Should().Be(Hashing.Sha256Hex(value2));

        var audit = Text(await client.CallToolAsync("vault_audit", new Dictionary<string, object?>()));
        audit.Should().Contain("exposed to a model: 0").And.NotContain("ROTATE or dismiss");
    }

    [RequiresCliFact]
    public async Task StageValue_Tool_Tags_SeenByModel_AppearsInAudit_NotEchoed()
    {
        using var harness = await VaultHarness.CreateAsync();
        await using var client = await ConnectAsync(harness);
        const string value = "tool-seen-value-77aa";

        var staged = Text(await client.CallToolAsync("vault_stage_value", new Dictionary<string, object?>
        {
            ["label"] = "Svcs/deploy",
            ["value"] = value,
            ["username"] = "svc",
            ["notes"] = "printed by service once",
        }));
        staged.Should().Contain("seen-by-model").And.NotContain(value);

        var stored = (await harness.Cli.ReadAttributeAsync(
            harness.StagingPath, VaultHarness.StagingPassword, null, "Svcs/deploy", "Password")).TrimEnd('\r', '\n');
        stored.Should().Be(value);

        var audit = Text(await client.CallToolAsync("vault_audit", new Dictionary<string, object?>()));
        audit.Should().Contain("Svcs/deploy").And.Contain("ROTATE or dismiss");

        // rotating the staged entry clears the exposure (that's the intended remedy).
        var rot = Text(await client.CallToolAsync("vault_rotate", new Dictionary<string, object?>
        {
            ["label"] = "Svcs/deploy",
        }));
        rot.Should().Contain("regenerated");
        audit = Text(await client.CallToolAsync("vault_audit", new Dictionary<string, object?>()));
        audit.Should().Contain("exposed to a model: 0");
    }

    [RequiresCliFact]
    public async Task AuditDismiss_SingleAndAll()
    {
        using var harness = await VaultHarness.CreateAsync();
        await using var client = await ConnectAsync(harness);

        var prov = ProvenanceStore.Load(harness.Paths);
        prov.Upsert("A/one", null, Origin.SeenByModel, "h1");
        prov.Upsert("A/two", null, Origin.SeenByModel, "h2");
        prov.Save(harness.Paths);

        var one = Text(await client.CallToolAsync("vault_audit_dismiss", new Dictionary<string, object?>
        {
            ["entryPath"] = "A/one",
        }));
        one.Should().Contain("Dismissed");
        ProvenanceStore.Load(harness.Paths).Records.Should().ContainSingle();

        var all = Text(await client.CallToolAsync("vault_audit_dismiss", new Dictionary<string, object?>()));
        all.Should().Contain("discarded");
        ProvenanceStore.Load(harness.Paths).Records.Should().BeEmpty();
    }

    [RequiresCliFact]
    public async Task SearchWithoutSession_GuidesToReader()
    {
        using var harness = await VaultHarness.CreateAsync();
        await using var client = await ConnectAsync(harness);
        var reply = Text(await client.CallToolAsync("vault_search", new Dictionary<string, object?> { ["term"] = "x" }));
        reply.Should().Contain("No reader session").And.Contain("keepassxc-mcp reader");
    }
}
